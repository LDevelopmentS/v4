#!/usr/bin/env python3
"""Builds js/app.js: the same ES modules joined into one classic script, so the tool also works
when index.html is opened straight from disk (file://), where browsers refuse to load modules.
The module files stay the source of truth. Re-run after editing any js/*.js:  python3 build-bundle.py"""
import re, pathlib
J = pathlib.Path(__file__).parent / 'js'
ORDER = ['storage','dom','config','states','links','store','history','table','si','guides-data','guides','protect','rail','theme','main']
out = ['/* GENERATED by build-bundle.py from the modules in this folder. Do not edit; edit the modules and rebuild. */',
       "'use strict';", 'var __M = {};']
for name in ORDER:
    src = (J / f'{name}.js').read_text()
    exports = []
    def imp(m):
        names = m.group(1).replace(' as ', ': ')
        return f"const {{{names}}} = __M['{m.group(2)}'];"
    src = re.sub(r"import\s*\{([^}]*)\}\s*from\s*'\./([\w-]+)\.js';", imp, src)
    def exp_decl(m): exports.append(m.group(2)); return m.group(1)
    src = re.sub(r"^export\s+((?:async\s+)?function\s+)(\w+)", lambda m: (exports.append(m.group(2)), m.group(1)+m.group(2))[1], src, flags=re.M)
    src = re.sub(r"^export\s+(const|let)\s+(\w+)", lambda m: (exports.append(m.group(2)), f"{m.group(1)} {m.group(2)}")[1], src, flags=re.M)
    def exp_list(m): exports.extend(x.strip() for x in m.group(1).split(',')); return ''
    src = re.sub(r"^export\s*\{([^}]*)\};?", exp_list, src, flags=re.M)
    out.append(f"/* ---- {name}.js ---- */\n(function(){{\n{src}\n__M['{name}'] = {{{', '.join(exports)}}};\n}})();")
(J / 'app.js').write_text('\n'.join(out) + '\n')
print('wrote js/app.js')
